/**
 * Trims the dead margin around each client logo and records the resulting
 * dimensions.
 *
 * The logos were lifted from the company's media library, where every file is
 * a 270x155 canvas with the mark centred inside it. On average ~55% of each
 * file is padding, which made the marks render at roughly a third of their
 * intended size in any fixed-height row. Trimming to the ink means a logo row
 * can size the marks themselves rather than their canvases.
 *
 * Logos that genuinely fill their canvas (those with a solid coloured
 * background, such as Edison Lithium) are left as they are — there is nothing
 * to trim.
 *
 * Safe to re-run: trimming an already-trimmed image is a no-op.
 *
 * Run with:  node scripts/trim-client-logos.mjs
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const DIR = "public/images/clients";
const OUT = "data/client-logo-sizes.generated.ts";

const files = (await readdir(DIR)).filter((f) => f.endsWith(".webp")).sort();
const sizes = {};
let trimmed = 0;

for (const file of files) {
  const full = path.join(DIR, file);
  // Read into memory first: on Windows sharp keeps the input file handle open,
  // and writing back to the same path then fails.
  const input = await readFile(full);
  const before = await sharp(input).metadata();

  let out;
  try {
    out = await sharp(input)
      .trim({ threshold: 12 })
      .webp({ quality: 92 })
      .toBuffer({ resolveWithObject: true });
  } catch {
    // A uniform image has nothing to trim; keep it untouched.
    sizes[file] = { width: before.width, height: before.height };
    continue;
  }

  // Guard against a threshold that eats the whole mark.
  if (out.info.width < 16 || out.info.height < 8) {
    sizes[file] = { width: before.width, height: before.height };
    continue;
  }

  if (out.info.width !== before.width || out.info.height !== before.height) {
    await writeFile(full, out.data);
    trimmed += 1;
  }
  sizes[file] = { width: out.info.width, height: out.info.height };
}

const body = Object.entries(sizes)
  .map(([file, s]) => `  "${file}": { width: ${s.width}, height: ${s.height} },`)
  .join("\n");

await writeFile(
  OUT,
  `// Generated by scripts/trim-client-logos.mjs — do not edit by hand.\n` +
    `// Intrinsic size of each trimmed client logo, used so next/image can\n` +
    `// reserve the right space and avoid layout shift.\n\n` +
    `export const clientLogoSizes: Record<string, { width: number; height: number }> = {\n` +
    `${body}\n};\n`,
);

console.log(
  `${files.length} logos processed, ${trimmed} trimmed. Sizes written to ${OUT}.`,
);
